"""Generates the network background pattern (Android VectorDrawable + SVG
preview) and the power icon, from the same geometry."""

import math
import random

W, H = 360, 640


def network():
    rnd = random.Random(7)
    pts = []
    # denser at the top, fading toward the bottom
    while len(pts) < 46:
        x, y = rnd.uniform(-10, W + 10), rnd.uniform(-10, H * 0.75)
        if all((x - a) ** 2 + (y - b) ** 2 > 38 ** 2 for a, b in pts):
            pts.append((x, y))
    lines = []
    for i, (x1, y1) in enumerate(pts):
        near = sorted(((x2 - x1) ** 2 + (y2 - y1) ** 2, j) for j, (x2, y2) in enumerate(pts) if j != i)
        for d2, j in near[:2]:
            if d2 < 95 ** 2 and (j, i) not in lines:
                lines.append((i, j))
    return pts, lines


def fade(y):
    return max(0.0, 1.0 - y / (H * 0.8))


def vector_xml():
    pts, lines = network()
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- generated by tools/icon/ui_assets.py -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="%ddp" android:height="%ddp"' % (W, H),
           '    android:viewportWidth="%d" android:viewportHeight="%d">' % (W, H)]
    for i, j in lines:
        (x1, y1), (x2, y2) = pts[i], pts[j]
        a = 0.10 * fade((y1 + y2) / 2)
        if a < 0.01:
            continue
        out.append('    <path android:pathData="M%.1f,%.1f L%.1f,%.1f" android:strokeColor="#FFFFFF" '
                   'android:strokeAlpha="%.3f" android:strokeWidth="1"/>' % (x1, y1, x2, y2, a))
    for x, y in pts:
        a = 0.28 * fade(y)
        if a < 0.02:
            continue
        r = 2.2
        out.append('    <path android:pathData="M%.1f,%.1f m-%.1f,0 a%.1f,%.1f 0 1,0 %.1f,0 a%.1f,%.1f 0 1,0 -%.1f,0" '
                   'android:fillColor="#5CF2D6" android:fillAlpha="%.3f"/>' % (x, y, r, r, r, 2 * r, r, r, 2 * r, a))
    out.append('</vector>')
    return "\n".join(out)


def svg_pattern():
    pts, lines = network()
    out = []
    for i, j in lines:
        (x1, y1), (x2, y2) = pts[i], pts[j]
        out.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="#FFF" stroke-opacity="%.3f"/>'
                   % (x1, y1, x2, y2, 0.10 * fade((y1 + y2) / 2)))
    for x, y in pts:
        out.append('<circle cx="%.1f" cy="%.1f" r="2.2" fill="#5CF2D6" fill-opacity="%.3f"/>' % (x, y, 0.28 * fade(y)))
    return "\n".join(out)


# power symbol on a 24x24 grid: open arc + vertical bar
POWER_ARC = "M7.05,5.64 A8,8 0 1,0 16.95,5.64"
POWER_BAR = "M12,2.5 L12,11"


def power_vector():
    return '''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
    <path android:pathData="%s" android:strokeColor="#FFFFFF"
        android:strokeWidth="2.2" android:strokeLineCap="round" android:fillColor="#00000000"/>
    <path android:pathData="%s" android:strokeColor="#FFFFFF"
        android:strokeWidth="2.2" android:strokeLineCap="round"/>
</vector>''' % (POWER_ARC, POWER_BAR)


if __name__ == "__main__":
    import sys
    res = sys.argv[1]
    open(res + "/drawable/brand_network.xml", "w").write(vector_xml() + "\n")
    open(res + "/drawable/brand_ic_power.xml", "w").write(power_vector() + "\n")
